/* ====== 软件模拟 I2C ======
 *
 * 不用 STM32 的 I2C1 外设, 把两根普通 GPIO 当 I2C 用, 自己拉时序:
 *   SCL(PB3): 推挽输出 —— 总线上只有主机驱动它, 推挽不会冲突
 *   SDA(PB4): 平时推挽输出, 读应答的第 9 个时钟切成输入上拉松开总线
 *
 * 为什么用推挽而不是开漏:
 *   开漏只能把线拉低, 高电平全靠外部上拉。早期用硬件 I2C1(开漏)时高电平只到
 *   1.82V 左右, 低于 SSD1306 认高的门槛(0.7*VDD 约 2.3V), 从机认不出高电平
 *   (那 1.82V 是屏的上拉偏弱, 还是当时就挂在已损坏的 PB8/PB9 上, 没分开验证过)。
 *   推挽由 CPU 直接把线顶到 3.3V, 不受上拉强弱影响。
 *
 * 为什么不用硬件 I2C1:
 *   I2C1 的两组脚位都不可用 —— 默认的 PB6/PB7 是右编码器(TIM4),
 *   重映射的 PB8/PB9 推挽顶高只有零点几伏(损坏)。I2C2 的 PB10/PB11
 *   是电机方向脚。硬件 I2C 在这块板子上没有落点。
 *
 * 注意: 推挽驱动 + 主机独占, 只适合点对点。要往这条总线上再挂一个从机
 *   (比如 MPU6050), 得先把 SCL/SDA 改成开漏并配合适的外部上拉, 否则从机
 *   拉低 SDA/SCL 时主机的推挽驱动器会跟它顶牛。
 */

/* ---- 引脚选择: 换脚只改下面这几行 ----
 *
 * PB3/PB4 出厂是 JTAG 的 JTDO / NJTRST, 但 HAL_MspInit() 已调过
 * __HAL_AFIO_REMAP_SWJ_NOJTAG(): JTAG 关掉、SWD 保留, 当普通 GPIO 没问题,
 * ST-Link 的下载和调试都不受影响。
 *
 * POS 的计算: PBn 占 bit(4n+3 : 4n), 即 POS = 4*n, 这是"绝对"位置 ——
 * I2C_PinCfg 会自己按 POS 是否 >= 32 选 CRL 还是 CRH。
 *   PB3 -> POS 12, PB4 -> POS 16   (都落在 CRL)
 *   PB8 -> POS 32, PB9 -> POS 36   (都落在 CRH; 别写成 0 / 4, 那是 PB0 / PB1)
 */
#define I2C_PORT            GPIOB
#define I2C_SCL_PIN         GPIO_PIN_3
#define I2C_SDA_PIN         GPIO_PIN_4
#define I2C_SCL_POS         12
#define I2C_SDA_POS         16

/* 半周期延时(空循环), 量级几微秒。SSD1306 只限最高 400kHz, 慢一点无所谓 */
#define I2C_DELAY()         do { for (volatile uint32_t d = 0; d < 40; d++) { } } while (0)

/* I2C 写控制字节: 0x00=命令, 0x40=数据 (SSD1306 在 I2C 下的 D/C# 位置) */
#define OLED_CTRL_CMD       0x00
#define OLED_CTRL_DATA      0x40

/* 从机不应答的累计次数. 屏没接/没上电时它只涨, 是"屏在不在线"的唯一信号 */
uint32_t g_i2c_nack_count = 0;

/*
 * 把某个引脚在 CRL/CRH 里的 nibble 改成 cfg: 0x3=推挽输出, 0x8=输入上拉.
 * pos 是"绝对位域起点"(PBn -> 4*n): 0~31 落在 CRL, 32~63 落在 CRH。
 */
static void I2C_PinCfg(uint32_t pos, uint32_t cfg)
{
    volatile uint32_t *cr;
    uint32_t shift;

    if (pos < 32)
    {
        cr = &I2C_PORT->CRL;
        shift = pos;
    }
    else
    {
        cr = &I2C_PORT->CRH;
        shift = pos - 32;
    }

    *cr = (*cr & ~(0xFUL << shift)) | (cfg << shift);
}

/* 把两根线配成普通推挽输出, 并置为总线空闲(两根都是高) */
static void I2C_Bus_Init(void)
{
    GPIO_InitTypeDef GPIO_InitStruct = {0};

    __HAL_RCC_GPIOB_CLK_ENABLE();

    GPIO_InitStruct.Pin = I2C_SCL_PIN | I2C_SDA_PIN;
    GPIO_InitStruct.Mode = GPIO_MODE_OUTPUT_PP;
    GPIO_InitStruct.Speed = GPIO_SPEED_FREQ_HIGH;
    HAL_GPIO_Init(I2C_PORT, &GPIO_InitStruct);

    HAL_GPIO_WritePin(I2C_PORT, I2C_SCL_PIN | I2C_SDA_PIN, GPIO_PIN_SET);
}

/* SDA 切成输入上拉: 松开总线, 让从机可以把它拉低(应答) */
static void I2C_SdaInput(void)
{
    I2C_PinCfg(I2C_SDA_POS, 0x8);
    I2C_PORT->BSRR = I2C_SDA_PIN;   /* ODR=1 选中上拉 */
}

/* SDA 切回推挽输出 */
static void I2C_SdaOutput(void)
{
    I2C_PinCfg(I2C_SDA_POS, 0x3);
}

/* 起始条件: SCL 高时 SDA 由高变低 */
static void I2C_Start(void)
{
    HAL_GPIO_WritePin(I2C_PORT, I2C_SDA_PIN, GPIO_PIN_SET);
    HAL_GPIO_WritePin(I2C_PORT, I2C_SCL_PIN, GPIO_PIN_SET);
    I2C_DELAY();
    HAL_GPIO_WritePin(I2C_PORT, I2C_SDA_PIN, GPIO_PIN_RESET);
    I2C_DELAY();
    HAL_GPIO_WritePin(I2C_PORT, I2C_SCL_PIN, GPIO_PIN_RESET);
    I2C_DELAY();
}

/* 停止条件: SCL 高时 SDA 由低变高 */
static void I2C_Stop(void)
{
    HAL_GPIO_WritePin(I2C_PORT, I2C_SDA_PIN, GPIO_PIN_RESET);
    HAL_GPIO_WritePin(I2C_PORT, I2C_SCL_PIN, GPIO_PIN_SET);
    I2C_DELAY();
    HAL_GPIO_WritePin(I2C_PORT, I2C_SDA_PIN, GPIO_PIN_SET);
    I2C_DELAY();
}

/* 写一个字节(高位先出), 顺带统计从机不应答的次数 */
static uint8_t I2C_WriteByte(uint8_t byte)
{
    uint8_t ack;

    for (uint8_t i = 0; i < 8; i++)
    {
        HAL_GPIO_WritePin(I2C_PORT, I2C_SCL_PIN, GPIO_PIN_RESET);
        if ((byte & 0x80) != 0)
        {
            HAL_GPIO_WritePin(I2C_PORT, I2C_SDA_PIN, GPIO_PIN_SET);
        }
        else
        {
            HAL_GPIO_WritePin(I2C_PORT, I2C_SDA_PIN, GPIO_PIN_RESET);
        }
        byte = (uint8_t)(byte << 1);
        I2C_DELAY();
        HAL_GPIO_WritePin(I2C_PORT, I2C_SCL_PIN, GPIO_PIN_SET);
        I2C_DELAY();
    }

    /* 第 9 个时钟: 松开 SDA, 读从机有没有把它拉低 */
    HAL_GPIO_WritePin(I2C_PORT, I2C_SCL_PIN, GPIO_PIN_RESET);
    I2C_SdaInput();
    I2C_DELAY();
    HAL_GPIO_WritePin(I2C_PORT, I2C_SCL_PIN, GPIO_PIN_SET);
    I2C_DELAY();

    ack = (HAL_GPIO_ReadPin(I2C_PORT, I2C_SDA_PIN) == GPIO_PIN_RESET) ? 1 : 0;

    HAL_GPIO_WritePin(I2C_PORT, I2C_SCL_PIN, GPIO_PIN_RESET);
    I2C_SdaOutput();

    if (ack == 0)
    {
        g_i2c_nack_count++;
    }
    return ack;
}

