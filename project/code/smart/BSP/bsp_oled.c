/* 一次完整传输: 起始 + 从机地址 + 控制字节 + 数据 + 停止 */
static void OLED_WriteBytes(uint8_t ctrl, const uint8_t *data, uint16_t len)
{
    I2C_Start();
    I2C_WriteByte((uint8_t)OLED_ADDR);      /* 从机地址, 写方向 */
    I2C_WriteByte(ctrl);                    /* 0x00=命令, 0x40=数据 */
    for (uint16_t i = 0; i < len; i++)
    {
        I2C_WriteByte(data[i]);
    }
    I2C_Stop();
}

/* 发送单字节命令 */
static void OLED_WriteCmd(uint8_t cmd)
{
    OLED_WriteBytes(OLED_CTRL_CMD, &cmd, 1);
}

/* 发送多字节数据(用于写GDDRAM页) */
static void OLED_WriteData(const uint8_t *data, uint16_t len)
{
    OLED_WriteBytes(OLED_CTRL_DATA, data, len);
}

/*
 * 定位到 (page, col) : page 0~7, col 0~127 (像素坐标, 非字符坐标)
 * 页寻址模式下: 先设页, 再设列地址的高/低字节
 */
static void OLED_SetPos(uint8_t page, uint8_t col)
{
    OLED_WriteCmd(0xB0 + page);                    /* 设页 */
    OLED_WriteCmd(0x00 + (col & 0x0F));            /* 列地址低4位 */
    OLED_WriteCmd(0x10 + ((col >> 4) & 0x0F));     /* 列地址高4位 */
}

/* 初始化 OLED */
void OLED_Init(void)
{
    I2C_Bus_Init();

    for (uint16_t i = 0; i < sizeof(OLED_INIT_CMDS); i++)
    {
        OLED_WriteCmd(OLED_INIT_CMDS[i]);
    }
    OLED_Clear();
}

/* 清屏: 8页, 每页128列写0x00 */
void OLED_Clear(void)
{
    uint8_t buf[128];
    memset(buf, 0x00, sizeof(buf));
    for (uint8_t page = 0; page < 8; page++)
    {
        OLED_SetPos(page, 0);
        OLED_WriteData(buf, sizeof(buf));
    }
}

/* 显示单个8x16字符: row=0~3(行), col=0~15(列) */
void OLED_ShowChar(uint8_t row, uint8_t col, char ch)
{
    if (row >= OLED_ROW_NUM || col >= OLED_COL_NUM) return;   /* 越界忽略 */

    uint16_t idx = (uint16_t)(uint8_t)ch;
    if (idx < 0x20) idx = 0x20;                 /* 不可见字符归一为空格 */
    if (idx >= 0x7F) idx = 0x20;                /* 只支持到 '~' */

    uint8_t col8 = col * 8;                     /* 字符首列像素坐标 */
    const uint8_t *f = FONT_8x16[idx - 0x20];

    /* 上半页: row*2 页, 写8字节(8列的上半8行) */
    OLED_SetPos(row * 2, col8);
    OLED_WriteData(f, 8);

    /* 下半页: row*2+1 页 */
    OLED_SetPos(row * 2 + 1, col8);
    OLED_WriteData(f + 8, 8);
}

/* 显示字符串, 自动逐字符横向排列 */
void OLED_ShowString(uint8_t row, uint8_t col, const char *str)
{
    while (*str && col < OLED_COL_NUM)
    {
        OLED_ShowChar(row, col, *str);
        str++;
        col++;
    }
}

/* 显示有符号整数(自动加正负号), 如 123 / -45
 * 说明: 手写整数转ASCII, 不依赖 sprintf/stdio, 节省Flash */
void OLED_ShowNum(uint8_t row, uint8_t col, int32_t num)
{
    char buf[12];
    uint8_t pos = 0;

    /* 处理负号 */
    if (num < 0)
    {
        buf[pos++] = '-';
        num = -num;
    }

    /* 至少显示一位 '0', 用倒序存数字再翻转 */
    uint8_t digits[10];
    uint8_t cnt = 0;
    do
    {
        digits[cnt++] = (uint8_t)(num % 10);
        num /= 10;
    } while (num > 0);

    while (cnt > 0)
    {
        buf[pos++] = (char)('0' + digits[cnt - 1]);
        cnt--;
    }
    buf[pos] = '\0';

    OLED_ShowString(row, col, buf);
}

/*
 * 显示一整行: 16个8x16字符正好占满128列
 *
 * 相比 OLED_ShowString 逐字符写(每字符两次定位, 每次定位3条命令),
 * 这里把整行的上半页拼成128字节、下半页拼成128字节, 各一次连写。
 * 页寻址模式下页内列地址自增, 但不会跨页, 所以两页要各设一次位置。
 *
 * 缓冲先清零再填: 空字模就是空格, 短字符串后面自动补白,
 * 上一帧多出来的字符会被一起覆盖 —— 这是不用先清屏也不残留的原因。
 *
 * 缓冲用 static: 屏只由显示任务独占访问, 不需要可重入, 这样省下 256 字节栈。
 */
void OLED_ShowLine(uint8_t row, const char *str)
{
    static uint8_t s_top[OLED_COL_NUM * 8];
    static uint8_t s_bot[OLED_COL_NUM * 8];
    uint8_t col = 0;

    if (row >= OLED_ROW_NUM) return;

    memset(s_top, 0x00, sizeof(s_top));
    memset(s_bot, 0x00, sizeof(s_bot));

    while (str[col] != '\0' && col < OLED_COL_NUM)
    {
        uint16_t idx = (uint16_t)(uint8_t)str[col];
        if (idx < 0x20) idx = 0x20;                 /* 不可见字符归一为空格 */
        if (idx >= 0x7F) idx = 0x20;                /* 只支持到 '~' */

        memcpy(&s_top[col * 8], FONT_8x16[idx - 0x20], 8);
        memcpy(&s_bot[col * 8], FONT_8x16[idx - 0x20] + 8, 8);
        col++;
    }

    OLED_SetPos(row * 2, 0);
    OLED_WriteData(s_top, sizeof(s_top));

    OLED_SetPos(row * 2 + 1, 0);
    OLED_WriteData(s_bot, sizeof(s_bot));
}
